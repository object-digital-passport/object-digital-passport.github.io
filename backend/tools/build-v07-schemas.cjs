/* Generate offline validators from schemas pinned from specifications d9e1a22. */
const fs = require('node:fs');
const path = require('node:path');
const Ajv2020 = require('ajv/dist/2020').default;
const standalone = require('ajv/dist/standalone').default;
const esbuild = require('esbuild');

(async () => {
  const root = path.resolve(__dirname, '..');
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
  for (const name of ['passport', 'generation', 'receipt', 'manifest']) {
    const schema = JSON.parse(fs.readFileSync(path.join(root, 'config/odp-0.7/schema', name + '.json'), 'utf8'));
    ajv.addSchema(schema, name);
  }
  const contents = standalone(ajv, { passport: 'passport', generation: 'generation', receipt: 'receipt', manifest: 'manifest' });
  const output = await esbuild.build({ stdin: { contents, resolveDir: root, sourcefile: 'odp-v07-schemas.generated.cjs', loader: 'js' }, bundle: true, platform: 'browser', format: 'iife', globalName: 'ODPV07Schemas', write: false, legalComments: 'inline' });
  const header = '/* Generated by tools/build-v07-schemas.cjs from ODP 0.7 schemas; Ajv MIT. */\n';
  const footer = '\nif (typeof module === "object" && module.exports) module.exports = ODPV07Schemas;\n';
  fs.writeFileSync(path.join(root, 'js/odp-v07-schemas.bundle.js'), header + output.outputFiles[0].text + footer);
})().catch(error => { console.error(error); process.exitCode = 1; });
